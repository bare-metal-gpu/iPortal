import Foundation

@main
struct LifecycleTests {
    static func main() {
        assert(keepsWatcherAfterQuit(explicitQuit: false, systemReason: nil), "Dock Quit must preserve the watcher")
        assert(keepsWatcherAfterQuit(explicitQuit: false, systemReason: 0), "Command-Q must preserve the watcher")
        assert(!keepsWatcherAfterQuit(explicitQuit: true, systemReason: nil), "menu-bar Quit must stop everything")
        for reason: UInt32 in [0x71756974, 0x73687574, 0x72657374, 0x726c676f] {
            assert(!keepsWatcherAfterQuit(explicitQuit: false, systemReason: reason), "system termination must never be blocked")
        }
        var list = USBDeviceListState()
        let device = PortalUSBDevice(serial: "phone", name: "My iPhone")
        list.update([device], at: 0)
        list.update([], at: 1)
        assert(list.devices.count == 1 && !list.devices[0].available, "a mode switch keeps the row but disables play")
        list.update([device], at: 2.2)
        assert(list.devices[0].available && list.nextExpiry == nil, "reattachment cancels pending removal")
        list.expire(at: 3.1)
        assert(list.devices.count == 1, "an old expiry cannot remove the reattached phone")
        list.update([], at: 4)
        list.update([], at: 5)
        list.expire(at: 6)
        assert(list.devices.isEmpty, "repeated metadata updates do not postpone real removal")
        list.update([device, PortalUSBDevice(serial: "other", name: "Second iPhone")], at: 7)
        assert(list.devices.count == 2, "each attached phone gets its own play action")
        assert(phoneUDID(fromUSBSerial: "0000814000000000000000A1") == "00008140-00000000000000A1")
        assert(phoneUDID(fromUSBSerial: "00008140-00000000000000A1") == "00008140-00000000000000A1")
        assert(phoneUDID(fromUSBSerial: "0123456789012345678901234567890123456789") == "0123456789012345678901234567890123456789")
        var invitations = USBInvitationGate()
        assert(invitations.attached("phone", at: 0), "a new connection can offer mirroring")
        assert(!invitations.attached("phone", at: 0.1), "duplicate notifications must not reopen a dismissed popover")
        invitations.detached("phone", at: 1)
        assert(!invitations.attached("phone", at: 2.3), "a capture mode switch is the same invitation")
        invitations.detached("phone", at: 3)
        assert(invitations.attached("phone", at: 6), "a later physical reconnect offers mirroring again")
        assert(!invitations.attached("phone", at: 7), "closing the mirror cannot re-prompt for an existing connection")
        assert(invitations.attached("another-phone", at: 7), "different phones have independent connection episodes")
        var usb = USBRecoveryWindow()
        assert(!usb.detached(at: 1), "unplugging a stable connection is immediate")
        usb.attached(at: 2)
        assert(usb.detached(at: 2.2), "capture startup can briefly re-enumerate USB")
        assert(usb.holdsDisconnect(at: 3))
        assert(!usb.holdsDisconnect(at: 3.5), "a real removal during recovery is still bounded")
        usb.attached(at: 3.5)
        assert(usb.holdsDisconnect(at: 3.55), "allow usbmuxd to catch up after each attachment")
        assert(usb.detached(at: 3.6))
        assert(usb.holdsDisconnect(at: 3.7))
        usb.finish()
        assert(!usb.detached(at: 3.8), "once video is ready, removal becomes immediate again")
        usb.attached(at: 4)
        assert(!usb.detached(at: 12.1), "continuous flapping cannot mask disconnection forever")
        var gate = VideoReadinessGate()
        func observe(_ state: String, _ epoch: Int, _ now: Double, device: String = "A", document: String = "page1", server: String = "server1") -> VideoReadinessGate.Change {
            gate.observe(state, deviceID: device, epoch: epoch, bridgeID: document, serverInstance: server, statusRevision: epoch, now: now)
        }
        assert(observe("ready", 1, 100).invalidated)
        assert(!gate.acceptsFrame(at: 99, now: 101))
        assert(gate.acceptsFrame(at: 101, now: 101))
        assert(!observe("ready", 1, 102).invalidated)
        assert(gate.acceptsFrame(at: 101, now: 102))
        // A brief network failure must invalidate readiness even if capture kept running.
        assert(observe("connecting", 2, 103).invalidated)
        assert(!gate.acceptsFrame(at: 104, now: 104))
        assert(observe("ready", 3, 105).invalidated)
        assert(!gate.acceptsFrame(at: 104, now: 105))
        assert(gate.acceptsFrame(at: 106, now: 106))
        // Reloads can reuse a numeric epoch; document identity still separates them.
        assert(observe("ready", 3, 107, document: "page2").invalidated)
        assert(!gate.acceptsFrame(at: 106, now: 107))
        // Same state, different phone/server must not retain the old video binding.
        assert(observe("ready", 3, 108, device: "B", document: "page2").deviceChanged)
        assert(!gate.acceptsFrame(at: 107, now: 108))
        assert(observe("ready", 3, 109, device: "B", document: "page2", server: "server2").invalidated)
        assert(observe("locked", 4, 110, device: "B").invalidated)
        assert(!gate.acceptsFrame(at: 111, now: 111))
        _ = observe("unrecognized", 5, 112)
        assert(gate.lifecycle == "connecting")
        _ = observe("ready", 6, 113)
        assert(!gate.acceptsFrame(at: 114, now: 118), "stalled frames are not live")
        gate.suspend(at: 119)
        assert(!gate.acceptsFrame(at: 120, now: 120), "wake/navigation waits for a new observation")

        // Cached readiness echoes cannot undo a native suspension.
        let stale = gate.observe("ready", deviceID: "A", epoch: 6, bridgeID: "page1", serverInstance: "server1", statusRevision: 6, now: 121)
        assert(!stale.accepted)
        let freshStatus = gate.observe("ready", deviceID: "A", epoch: 6, bridgeID: "page1", serverInstance: "server1", statusRevision: 7, now: 122)
        assert(freshStatus.accepted && freshStatus.newStatus && freshStatus.invalidated)
        let regression = gate.observe("ready", deviceID: "A", epoch: 5, bridgeID: "page1", serverInstance: "server1", statusRevision: 8, now: 123)
        assert(!regression.accepted)
        let ack = gate.observe("ready", deviceID: "A", epoch: 6, bridgeID: "page1", serverInstance: "server1", statusRevision: 7, now: 124)
        assert(ack.accepted && !ack.newStatus, "readiness acknowledgements are not control-plane heartbeats")

        var cableGate = VideoReadinessGate()
        func cable(_ state: String, _ revision: Int, _ connection: String) -> VideoReadinessGate.Change {
            cableGate.observe(state, deviceID: "A", epoch: revision, bridgeID: "page", serverInstance: "server",
                              statusRevision: revision, now: Double(revision), connectionID: connection)
        }
        _ = cable("ready", 1, "7")
        assert(!cable("disconnected", 2, "7").deviceChanged, "unplug retains the same phone's frozen frame")
        let replug = cable("connecting", 3, "9")
        assert(replug.reattached && !replug.deviceChanged, "reattach resets capture retries without discarding the frame")
        assert(!cable("ready", 4, "9").reattached, "ordinary ready polls must not reset the failure budget")
        assert(cable("ready", 5, "10").reattached, "a quick replug between polls still invalidates the old capture")
        assert(!cableGate.acceptsFrame(at: 4.9, now: 5.1))
        assert(cableGate.acceptsFrame(at: 5.1, now: 5.1))
        cableGate.disconnect(at: 6)
        assert(cableGate.lifecycle == "disconnected")
        assert(!cableGate.acceptsFrame(at: 6.1, now: 6.1), "hardware removal freezes before web polling")
        let preEvent = cableGate.observe("ready", deviceID: "A", epoch: 5, bridgeID: "page", serverInstance: "server",
                                       statusRevision: 5, now: 6.2, connectionID: "10")
        assert(!preEvent.accepted, "pre-detach ready echo must not undo the hardware event")

        var budget = CaptureRetryBudget()
        assert(budget.beginAttempt(at: 0))
        budget.failed()
        assert(budget.beginAttempt(at: 1))
        budget.healthy(at: 2)
        budget.failed()
        assert(!budget.beginAttempt(at: 3), "one good frame cannot erase retry exhaustion")
        budget.healthy(at: 4)
        budget.healthy(at: 14)
        assert(budget.beginAttempt(at: 15), "sustained healthy video replenishes attempts")
        budget.failed()
        assert(budget.beginAttempt(at: 16))
        assert(!budget.beginAttempt(at: 17))
        assert(budget.beginAttempt(at: 77), "cooldown eventually permits recovery")
        print("Native identity, transient failure, fresh-frame and retry-budget tests passed.")
    }
}
